#!/usr/bin/env python3
"""Integrate the user's *already prepared* Kotoba N5 ONNX Lab v4.1 bundles.
No cloud synthesis, no audio pre-rendering, no permanent PCM caching.
Generates deterministic offline SentencePiece token indexes for shipped deck texts.
Example:
 python tools/prepare_kotoba_onnx.py --lab ../kotoba_n5_onnx_pages_v4_1
"""
from __future__ import annotations
import argparse
import json
import math
import re
import shutil
import urllib.request
from pathlib import Path

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent
SPLIT_RE=re.compile(r'(?<=[。！？.!?])\s*')
JP_REPLACE={'、':',','。':'.','！':'!','？':'?'}
IT_SEPARATORS={'comma':', ','dash':' - ','oppure':' oppure '}
FORM_NAMES={
 'て形':('Forma te','Te form'),'ます形':('Forma masu','Masu form'),
 'ない形':('Forma nai, negativa','Nai negative form'),'た形':('Forma ta, passata','Ta past form'),
 '可能形':('Forma potenziale','Potential form'),'丁寧形':('Forma cortese','Polite form'),
 '過去形':('Forma passata','Past form'),'否定形':('Forma negativa','Negative form'),
 '連体形':('Forma attributiva','Attributive form'),'補語形':('Forma ni','Ni form'),
 '副詞形':('Forma avverbiale','Adverbial form'),'否定過去':('Forma negativa passata','Past negative form'),
 '条件形':('Forma condizionale','Conditional form')
}
BUNDLES=('ja','it','en')

# The Lab intentionally publishes only browser inference files. Its Python
# tokenizer, BOS tensor and Mimi encoder stay in the download cache. A v4.1
# preparation may reuse the v4 cache (the Lab manifest does not record this).
BUNDLE_DIRECTORIES={'ja':'japanese_local','it':'italian','en':'english_2026-04'}
LAB_FOLDER_NAMES=('kotoba_n5_onnx_pages_v4_1','kotoba_n5_onnx_pages_v4',
                  'kotoba_n5_onnx_pages_v3','kotoba_n5_onnx_pages_v2')


def source_candidates(lab:Path,lang:str,filename:str):
    bundle=BUNDLE_DIRECTORIES[lang]
    # Preserve the exact asset generated by the selected Lab, when present.
    yield lab/'assets'/lang/filename
    seen=set()
    for sibling in (lab,*(lab.parent/name for name in LAB_FOLDER_NAMES)):
        sibling=sibling.resolve()
        if sibling in seen:continue
        seen.add(sibling)
        # All these are valid source positions, but NOT browser-deployed assets.
        yield sibling/'_download_models'/'onnx'/bundle/filename
        yield sibling/'assets'/lang/filename
    yield lab.parent/'_download_models'/'onnx'/bundle/filename
    yield lab.parent/'exporter'/'pocket-tts-onnx'/'onnx'/bundle/filename
    yield lab.parent/'exporter'/'onnx'/bundle/filename


def find_source_file(lab:Path,lang:str,filename:str):
    for candidate in source_candidates(lab,lang,filename):
        if candidate.is_file():return candidate
    return None


def missing_source_message(lab:Path,lang:str,filename:str):
    roots='; '.join(str(p.parent) for p in source_candidates(lab,lang,filename))
    return (f'File mancante {lang}/{filename}. Controllati: {roots}. '
            'Se la Lab v4.1 ha riutilizzato la cache v4, mantieni entrambe le '
            'cartelle nella stessa directory e riprova.')



def normalize_it(text,variant):
 return re.sub(r'\s+',' ',re.sub(r'\s*;\s*',IT_SEPARATORS[variant],text)).strip()


def spoken_text(text,lang,type_name,variant='oppure',context=False):
 text=text.strip()
 if type_name=='formLabel':
  label=text[0].lower()+re.sub(r'[.!?]+$', '', text[1:]) if text else ''
  if lang=='it':text='Adesso ascolta la '+label+'.'
  elif lang=='en':text='Now listen to the '+label+'.'
 if lang=='it':
  text=normalize_it(text,variant)
  if type_name=='meaning' and context:text='In italiano significa '+text.rstrip('.!?')+'.'
 elif lang=='en' and type_name=='meaning' and context:
  text='In English, it means '+text.rstrip('.!?')+'.'
 return re.sub(r'\s+',' ',text).strip()


def prepare_prompt(text,lang,meta,ja_mapping):
 if lang=='ja':
  for src,dst in ja_mapping.items():text=text.replace(src,dst)
 text=text.strip().replace('\n',' ').replace('\r',' ')
 if not text:return ''
 if not text[0].isupper():text=text[0].upper()+text[1:]
 if text[-1].isalnum():text+='.'
 if meta.get('pad_with_spaces_for_short_inputs',False) and len(text.split())<5:text=' '*8+text
 return text


def tokenize_docs(tokenizers,metas,deck,ja_mapping):
 tokens={lang:{} for lang in BUNDLES}
 cards=deck.get('cards',[])
 for card in cards:
  meaning=card.get('meaning') or {}
  if not isinstance(meaning,dict):meaning={'it':meaning,'en':card.get('meaningEn','')}
  grouped=[('ja',card.get('jp'),'word')]
  grouped.extend((lang,meaning.get(lang),'meaning') for lang in ('it','en'))
  for form in card.get('forms',[]):
   grouped.append(('ja',form.get('jp'),'form'))
   label=form.get('label')
   if label:
    it,en=FORM_NAMES.get(label,(label,label))
    if label=='連体形' and card.get('pos')=='na':it,en='Forma na, attributiva','Na attributive form'
    grouped.extend([('it',it,'formLabel'),('en',en,'formLabel')])
  # A session may request the alternative legacy example collection.
  for ex in [*(card.get('examples') or []),*(card.get('legacyExamples') or [])]:
   grouped.extend((lang,ex.get(field),'example') for lang,field in [('ja','jp'),('it','it'),('en','en')])
  for lang,text,kind in grouped:
   if not isinstance(text,str) or not text.strip():continue
   contexts=[False,True] if kind=='meaning' and lang in ('it','en') else [False]
   variants=IT_SEPARATORS if lang=='it' and ';' in text else ('oppure',)
   for context in contexts:
    for variant in variants:
     spoken=spoken_text(text,lang,kind,variant,context)
     if spoken in tokens[lang]:continue
     segments=[]
     for segment in SPLIT_RE.split(spoken):
      if not segment.strip():continue
      prepared=prepare_prompt(segment,lang,metas[lang],ja_mapping)
      if not prepared:continue
      ids=tokenizers[lang].Encode(prepared,out_type=int)
      if ids:segments.append({'text':segment,'prepared':prepared,'tokens':ids})
     if segments:tokens[lang][spoken]=segments
 # Story playback is not part of a card plan but uses the same ONNX speech adapter.
 for story in deck.get('stories',[]):
  for ex in story.get('segments',[]):
   for lang in BUNDLES:
    text=ex.get('jp' if lang=='ja' else lang)
    if not isinstance(text,str) or not text.strip():continue
    spoken=spoken_text(text,lang,'story')
    if spoken in tokens[lang]:continue
    chunks=[]
    for segment in SPLIT_RE.split(spoken):
     if not segment.strip():continue
     prepared=prepare_prompt(segment,lang,metas[lang],ja_mapping)
     ids=tokenizers[lang].Encode(prepared,out_type=int)
     if ids:chunks.append({'text':segment,'prepared':prepared,'tokens':ids})
    if chunks:tokens[lang][spoken]=chunks
 return tokens


def build_indexes(root:Path,manifest:dict,ja_yaml:Path|None):
 try:import sentencepiece as spm
 except ImportError as ex:raise RuntimeError('Installa: pip install sentencepiece') from ex
 tokenizers={};metas={}
 for lang in BUNDLES:
  base=root/'onnx'/'assets'/lang
  sp=spm.SentencePieceProcessor()
  if not sp.Load(str(base/'tokenizer.model')):raise RuntimeError('Tokenizer invalido: '+str(base))
  tokenizers[lang]=sp;metas[lang]=json.loads((base/'bundle.json').read_text(encoding='utf-8'))
 ja_mapping=JP_REPLACE.copy()
 if ja_yaml and ja_yaml.exists():
  import yaml
  cfg=yaml.safe_load(ja_yaml.read_text(encoding='utf-8')) or {}
  if isinstance(cfg.get('replace_characters'),dict):ja_mapping=cfg['replace_characters']
 index_paths={}
 for name in ('n4-core','n4-final-kotoba-drive','n5-final-kotoba-drive'):
  deck_path=root/'decks'/f'{name}.json'
  if not deck_path.exists():continue
  deck=json.loads(deck_path.read_text(encoding='utf-8'))
  shards={};cards=deck['cards'];shard_size=20
  total_bytes=0
  for start in range(0,len(cards),shard_size):
   group=cards[start:start+shard_size]
   subdeck={'cards':group,'stories':[]}
   # The full source story set is tokenized separately in the first shard for story playback.
   payload={'version':2,'deckId':deck['deckId'],'tokens':tokenize_docs(tokenizers,metas,subdeck,ja_mapping)}
   filename=f'onnx/tokens-{name}-{start//shard_size:03d}.json'
   (root/filename).write_text(json.dumps(payload,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
   total_bytes+=(root/filename).stat().st_size
   for card in group:shards[str(card['id'])]='./'+filename
  # Story playback is only used from the current deck. A dedicated shard avoids
  # forcing every regular card to load the story dictionary.
  story_url=None
  if deck.get('stories'):
   payload={'version':2,'deckId':deck['deckId'],'tokens':tokenize_docs(tokenizers,metas,{'cards':[],'stories':deck['stories']},ja_mapping)}
   story_url=f'./onnx/tokens-{name}-stories.json'
   (root/story_url[2:]).write_text(json.dumps(payload,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
  index_paths[deck['deckId']]={'shards':shards,'stories':story_url}
  print(f'Token index {name}: {len(cards)} card / {len(set(shards.values()))} shard / {total_bytes/1048576:.1f} MiB',flush=True)
 manifest['tokenIndexes']=index_paths
 return manifest


def add_english_male(root:Path,manifest:dict,sample:Path|None,download:bool,encoder_source:Path|None):
 cfg=manifest['languages']['en'];en=root/'onnx'/'assets'/'en'
 if sample is None and (root/'tools'/'voices'/'vctk_p226_023_enhanced.wav').is_file():
  sample=root/'tools'/'voices'/'vctk_p226_023_enhanced.wav'
 if sample is None and download:
  try:
   from huggingface_hub import hf_hub_download
   sample=Path(hf_hub_download(repo_id='kyutai/tts-voices',filename='vctk/p226_023_enhanced.wav',
                              local_dir=str(root/'tools'/'_voice_samples')))
   print('Voce inglese maschile VCTK p226 ottenuta dal repository pubblico Kyutai')
  except Exception as e:
   print(f'ATTENZIONE: impossibile ottenere voce maschile EN: {e}')
 if sample is None or not sample.exists():
  print('Voce inglese maschile non incorporata; usa --male-en-wav per un WAV locale')
  return
 try:
  import numpy as np,soundfile as sf,onnxruntime as ort
  from scipy.signal import resample_poly
 except ImportError as e:raise RuntimeError('Per la voce maschile: pip install onnxruntime soundfile scipy numpy') from e
 # Find source encoder; unlike the 4 browser models, encoder is needed ONLY at preparation time.
 candidates=[encoder_source, root/'onnx'/'assets'/'en'/'mimi_encoder.onnx',
             root.parent/'kotoba_n5_onnx_pages_v4_1'/'_download_models'/'onnx'/'english_2026-04'/'mimi_encoder.onnx',
             root.parent/'kotoba_n5_onnx_pages_v4'/'_download_models'/'onnx'/'english_2026-04'/'mimi_encoder.onnx']
 encoder=next((p for p in candidates if p and p.is_file()),None)
 if not encoder:raise FileNotFoundError('Manca mimi_encoder.onnx inglese: passa --english-encoder PATH')
 audio,sr=sf.read(sample,dtype='float32',always_2d=True);audio=audio.mean(axis=1)
 meta=json.loads((en/'bundle.json').read_text(encoding='utf-8'))
 sample_rate=int(meta['sample_rate'])
 if sr!=sample_rate:
  g=math.gcd(sr,sample_rate);audio=resample_poly(audio,sample_rate//g,sr//g).astype('float32')
 model=ort.InferenceSession(str(encoder),providers=['CPUExecutionProvider'])
 voice=np.asarray(model.run(None,{'audio':audio.reshape(1,1,-1).astype('float32')})[0],dtype=np.float32)
 while voice.ndim>3:voice=voice.squeeze(0)
 if voice.ndim==2:voice=voice[None]
 if voice.ndim!=3 or voice.shape[0]!=1:raise ValueError(f'Forma encoder inglese: {voice.shape}')
 if meta.get('insert_bos_before_voice'):
  bos=np.load(en/'bos_before_voice.npy').astype(np.float32)
  if not np.allclose(voice[:,:1,:],bos,atol=1e-4,rtol=1e-4):voice=np.concatenate([bos,voice],axis=1)
 target=en/'voices'/'vctk_p226.f32';target.parent.mkdir(exist_ok=True)
 np.ascontiguousarray(voice.astype('<f4')).tofile(target)
 cfg['voices']['vctk_p226']={'label':'VCTK p226 · maschile EN (CC BY 4.0)','file':'voices/vctk_p226.f32',
                             'frames':int(voice.shape[1]),'dim':int(voice.shape[2]),'source':str(sample.name)}
 print(f'Inglese maschile: {voice.shape[1]} frame, {voice.shape[2]} dim',flush=True)



def prepare_ort_vendor(root:Path):
 """Optional: pin the exact ORT runtime for GitHub Pages and offline app-shell caching.
 The ONNX models themselves remain browser HTTP-cache-only, to limit storage cost.
 """
 vendor=root/'vendor';vendor.mkdir(parents=True,exist_ok=True)
 files=('ort.min.js','ort-wasm-simd-threaded.wasm','ort-wasm-simd-threaded.mjs')
 base='https://cdn.jsdelivr.net/npm/onnxruntime-web@1.20.0/dist/'
 for name in files:
  dest=vendor/name
  if dest.is_file() and dest.stat().st_size>2000:continue
  try:
   with urllib.request.urlopen(base+name,timeout=35) as response, dest.open('wb') as out:
    shutil.copyfileobj(response,out)
   if dest.stat().st_size<2000:raise IOError('File troppo piccolo')
   print(f'Runtime locale: {dest.name} ({dest.stat().st_size/1048576:.1f} MiB)')
  except Exception as error:
   dest.unlink(missing_ok=True)
   # Do not leave a local JS with a missing WASM: the worker must then use the CDN.
   (vendor/'ort.min.js').unlink(missing_ok=True)
   print(f'ATTENZIONE: runtime ORT locale incompleto ({name}): {error}. CDN resta disponibile.')
   return

def main():
 ap=argparse.ArgumentParser()
 ap.add_argument('--lab',type=Path,required=True,help='Percorso della cartella kotoba_n5_onnx_pages_v4_1 con assets/manifest.json')
 ap.add_argument('--root',type=Path,default=ROOT)
 ap.add_argument('--ja-yaml',type=Path)
 ap.add_argument('--male-en-wav',type=Path,help='WAV maschile inglese locale, evita il download')
 ap.add_argument('--english-encoder',type=Path,help='mimi_encoder.onnx inglese per creare nuova voce')
 ap.add_argument('--no-male-download',action='store_true')
 ap.add_argument('--no-ort-vendor',action='store_true',help='Usa il CDN ONNX Runtime Web anziche salvare JS/WASM sul sito')
 ap.add_argument('--tokens-only',action='store_true',help='Rigenera soltanto gli indici SentencePiece usando gli asset ONNX gia preparati')
 args=ap.parse_args();root=args.root.resolve();lab=args.lab.resolve()
 if args.tokens_only:
  manifest_file=root/'onnx'/'manifest.json'
  if not manifest_file.is_file():ap.error('Manca onnx/manifest.json: completa prima la preparazione ONNX')
  previous=json.loads(manifest_file.read_text(encoding='utf-8'))
  index_manifest=build_indexes(root,previous,args.ja_yaml or (lab.parent/'source'/'japanese.yaml'))
  manifest_file.write_text(json.dumps(index_manifest,ensure_ascii=False,indent=2),encoding='utf-8')
  print('OK: indici rigenerati, voci e modelli esistenti invariati.')
  return
 source_manifest=lab/'assets'/'manifest.json'
 if not source_manifest.exists():ap.error(f'Completa prima run_test.ps1 della v4.1; manca: {source_manifest}')
 original=json.loads(source_manifest.read_text(encoding='utf-8'))
 dest=root/'onnx'/'assets';dest.mkdir(parents=True,exist_ok=True)
 manifest={'version':'kotoba-drive-onnx-v1','languages':{},'tokenIndexes':{}}
 for lang in BUNDLES:
  cfg=original['languages'][lang];src=lab/'assets'/lang;target=dest/lang
  target.mkdir(exist_ok=True)
  required=['bundle.json','tokenizer.model','bos_before_voice.npy',*cfg['modelFiles'].values()]
  required.extend(v['file'] for v in cfg['voices'].values())
  # Lab v4.1 omits tokenizer/BOS from its browser assets on purpose.
  # Find those files in the Lab v4.1 or reused Lab v4 download cache.
  for name in set(required):
   origin=find_source_file(lab,lang,name)
   if origin is None:ap.error(missing_source_message(lab,lang,name))
   if origin.parent!=src and name in ('tokenizer.model','bos_before_voice.npy'):
    print(f'  {lang}/{name}: recuperato da {origin}',flush=True)
   output=target/name;output.parent.mkdir(parents=True,exist_ok=True)
   if not output.exists() or output.stat().st_size!=origin.stat().st_size:shutil.copy2(origin,output)
  manifest['languages'][lang]={**cfg,'directory':'./onnx/assets/'+lang+'/'}
  print(f'Modello {lang}: {list(cfg["voices"])}',flush=True)
 # The 40 MB offline encoder belongs to the build process only, not GitHub Pages.
 encoder_source=args.english_encoder or find_source_file(lab,'en','mimi_encoder.onnx')
 if encoder_source is not None and encoder_source.is_file():
  print(f'Encoder inglese per voce maschile: {encoder_source}',flush=True)
 add_english_male(root,manifest,args.male_en_wav,not args.no_male_download,encoder_source)
 deployed_encoder=dest/'en'/'mimi_encoder.onnx'
 if deployed_encoder.is_file():deployed_encoder.unlink()
 manifest=build_indexes(root,manifest,args.ja_yaml or (lab.parent/'source'/'japanese.yaml'))
 if not args.no_ort_vendor:prepare_ort_vendor(root)
 (root/'onnx'/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
 print('OK: '+str(root/'onnx'/'manifest.json'))
 print('Nota: i file .onnx non sono inclusi nello ZIP sorgente. Esegui questo script sul PC.')

if __name__=='__main__':main()
